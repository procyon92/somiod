using SOMIOD.Models;
using System;
using System.Collections.Generic;
using System.Configuration;
using System.Data.SqlClient;
using System.Linq;
using System.Net;
using System.Web.Http;
using System.Web.Http.Description;

namespace SOMIOD.Controllers
{
    [RoutePrefix("api/somiod")]
    public class ApplicationController : ApiController
    {
        // Connection String (Garante que no Web.config tens <add name="ConnStr" ... />)
        private string connectionString = ConfigurationManager.ConnectionStrings["ConnStr"].ConnectionString;

        // =============================================================
        // 1. OPERAÇÕES NA RAIZ DO SISTEMA (api/somiod/)
